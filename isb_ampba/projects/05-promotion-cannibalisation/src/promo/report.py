"""Write the number-bearing documents from outputs/summary.json (no number is typed by hand)."""
from __future__ import annotations

from pathlib import Path

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def _g(x: float | None, nd: int = 0) -> str:
    return "n/a" if x is None else f"{x:,.{nd}f}"


def _gbp(x: float | None, nd: int = 0) -> str:
    return "n/a" if x is None else (f"-£{abs(x):,.{nd}f}" if x < 0 else f"£{x:,.{nd}f}")


def _inr(x: float | None) -> str:
    return "n/a" if x is None else (f"-₹{abs(x):,.0f}" if x < 0 else f"₹{x:,.0f}")


def memo(s: dict) -> str:
    """DECISION_MEMO.md following the template in the case-study spec."""
    r, w, o, k = s["reference"], s["sweep"], s["optimiser"], s["kpi_classification"]
    d = s["demand"]; f = s["families"]
    n_fam = o["n_candidate_families"]
    cal = o["calendar"]; dash = o["dashboard_promoted_only_rank"]; top = o["top_revenue_rank"]
    tor = s["tornado"][0]
    return f"""# Decision memo - Judge promotions on family contribution, not SKU uplift

*All numbers below are read from `outputs/summary.json` (generated by `analysis/run_analysis.py`, seed {s['seed']}). Margin and promotions are ASSUMPTIONS / inferences - see Risks.*

**Decision requested:** Change the promotion approval metric from promoted-SKU uplift to family net contribution (direct - subsidy - cannibalised + halo).

**Recommendation:** Approve a promotion only when family net > 0 under the base case **and** the break-even elasticity is less elastic than the SKU's estimated elasticity (break-even multiplier < 1). Use the optimiser's {o['horizon_weeks']}-week plan below; it also leaves most families undiscounted, which is a legitimate answer.

**Impact (reference promo: {int(r['discount'] * 100)}% off the top-{r['n_skus']} SKUs by revenue for {r['promo_weeks']} weeks, unit margin {int(round(r['margin_assumed'] * 100))}% assumed, GBP to INR {r['gbp_to_inr']:g}):**
promoted-only view: {r['n_looks_profitable_promoted_only']} of {r['n_skus']} look profitable (total {_gbp(r['promoted_only_total_gbp'])});
family view: {r['n_profitable_family']} of {r['n_skus']} are profitable ({r['n_dashboard_trap']} dashboard traps: profitable promoted-only, unprofitable for the family; {r['n_hidden_by_dashboard']} the other way round) (**family net total {_gbp(r['family_net_total_gbp'])} = {_inr(r['family_net_total_inr'])}**, median per SKU {_gbp(r['family_net_median_gbp'])}).
Cannibalised margin {_gbp(r['cannibalised_total_gbp'])}; halo {_gbp(r['halo_total_gbp'])}; subsidy {_gbp(r['subsidy_total_gbp'])}; direct uplift {_gbp(r['direct_total_gbp'])}.
The sign of the total depends on the assumed margin and outside share (see sensitivity table in the README; `outputs/reference_sensitivity.csv`).

**Sweep ({w['n_draws']:,} Latin-hypercube assumption draws at {int(w['discount'] * 100)}% off):** promoted-only profitable in {_g(w['pct_promoted_only_profitable'], 1)}% of conditions; family net profitable in {_g(w['pct_family_profitable'], 1)}%; {_g(w['pct_dashboard_trap'], 1)}% are "dashboard traps" (profitable for the SKU, unprofitable for the family). Of the conditions that look profitable on the dashboard, {_g(w['pct_family_profitable_given_promoted_only_profitable'], 1)}% are also profitable for the family. Median break-even elasticity {_g(w['break_even_elasticity_median'], 2)} (10th-90th percentile {_g(w['break_even_elasticity_p10'], 2)} to {_g(w['break_even_elasticity_p90'], 2)}). Reference promo: median break-even elasticity {_g(r['break_even_eps_median'], 2)} vs estimated elasticities; **median break-even multiplier {_g(r['break_even_multiplier_median'], 2)}** (break-even / estimated elasticity; above 1 means the SKU would have to be more price-sensitive than estimated for the promo to pay).
The assumption that moves the answer most (tornado, one-at-a-time): **{tor['param']}**.

**Optimiser:** discounting {o['n_families_discounted_calendar']} of {n_fam} candidate families (top families by revenue) in the {o['horizon_weeks']}-week calendar at a subsidy budget of {_gbp(o['budget_gbp'])} yields {_gbp(cal['family_net'])} expected family net (subsidy used {_gbp(cal['subsidy'])}), versus {_gbp(dash['family_net'])} for a dashboard-ranked plan ({dash['n_promos']} promos at one common discount) and {_gbp(top['family_net'])} for promoting the top-revenue SKUs. The budget is {'binding' if any(b['binding'] for b in o['budget_sensitivity'] if abs(b['budget_frac'] - 0.30) < 1e-9) else 'not binding'} at the configured fraction; it binds at the tighter fractions shown in `outputs/summary.json` (`optimiser.budget_sensitivity`).

**Classification KPI (simulation truth = drawn parameters):** the dashboard rule (promoted-only > 0) classifies {_g(k['dashboard_accuracy_pct'], 1)}% of conditions correctly; the family-net rule with parameters known to +/-10% / 25% / 50% relative noise classifies {_g(k['engine_accuracy_pct_noise_10'], 1)}% / {_g(k['engine_accuracy_pct_noise_25'], 1)}% / {_g(k['engine_accuracy_pct_noise_50'], 1)}% correctly.

**Risks & limitations:**
- No cost data: margin ({int(round(r['margin_assumed'] * 100))}%) is an assumption; conclusions flip within the swept margin range.
- No promotion flags: price drops are inferred and not randomised, so elasticities are associations ({d['n_valid_negative']} of {d['n_skus']} SKUs had an identifiable estimate; {d['source_counts'].get('prior', 0)} SKUs use the prior {d['prior_elasticity']}; {d['n_positive_dropped']} positive estimates were dropped). Where price does not vary we rely on priors and the sweep.
- Wholesale customers buy variants together (median co-purchase share {_g(100 * f['copurchase_median_share'], 1)}%; {f['n_weak_substitute_families']} of {f['copurchase_n_families_checked']} multi-SKU families flagged weak substitutes), so substitution may be overstated; MNL assumes IIA; one promo window only (no pull-forward, stockpiling or competitor reaction).

**Next steps:** run controlled promotions with sibling tracking (owner: category management + pricing analytics); replace assumed margins with finance data; validate against a dataset with real promo flags (Dunnhumby); re-run this engine monthly and monitor realised vs predicted family net.
"""


def model_card(s: dict) -> str:
    """MODEL_CARD.md."""
    d, f, b, r, w = s["demand"], s["families"], s["baskets"], s["reference"], s["sweep"]
    data = s["data"]; m = s["mnl_checks"]
    return f"""# Model card - Promotion Cannibalisation Engine

*Numbers from `outputs/summary.json`; seed {s['seed']}.*

## Intended use
Ex-ante scoring of a proposed discount on one SKU of a product family: direct uplift, subsidy on baseline units, cannibalised sibling margin and basket halo, summarised as **family net contribution**; plus a discount-level optimiser and an assumption sweep. Decision support for category managers, not an automatic pricing system.

## Out-of-scope use
Causal claims about price elasticity; margin forecasts without finance cost data; promotions longer than a few weeks (no pull-forward / post-promo dip); competitor-driven pricing; markets other than a UK gift-ware wholesale/retail mix.

## Training / calibration data
UCI Online Retail II (id 502), {data['date_min']} to {data['date_max']}: {data['clean_lines']:,} clean sales lines, {data['invoices']:,} invoices, {data['skus']:,} SKUs, £{data['revenue_gbp']:,.0f} revenue. No costs and no promotion flags exist in the data. Fully cancelled bulk orders (qty >= 10,000) are removed.

## Components and diagnostics
| Component | Result |
|---|---|
| Families (TF-IDF + agglomerative) | {f['n_families']:,} families, {f['n_multi_sku_families']} multi-SKU (max size {f['max_family_size']}); co-purchase median {_g(100 * f['copurchase_median_share'], 1)}%, {f['n_weak_substitute_families']} weak-substitute families (cannibalisation capped) |
| Basket halo (FP-Growth) | {b['n_rules']} cross-family rules, {b['n_skus_with_halo']} SKUs with halo |
| Price response (log-log, month effects, HC1) | {d['n_eligible']} eligible SKUs, {d['n_valid_negative']} negative estimates, {d['n_positive_dropped']} positive dropped; median {_g(d['eps_hat_median'], 2)}; pooled SKU+week FE {_g(d['pooled_two_way_fe']['eps'], 2)} (se {_g(d['pooled_two_way_fe']['se'], 3)}); sources: {d['source_counts']} |
| MNL calibration | max share-sum error {m['max_share_sum_error']:.1e}; max relative own-elasticity error at d=0.1% {m['max_rel_elasticity_error_d0.001']:.2%} |
| Engine identity | family_net = direct - subsidy - cannibalised + halo to 1e-6 (unit test) |

## Metrics (no trained predictor; business metrics)
Reference promo ({int(r['discount'] * 100)}% off top-{r['n_skus']}): family net {_gbp(r['family_net_total_gbp'])}, promoted-only {_gbp(r['promoted_only_total_gbp'])}. Sweep ({w['n_draws']:,} draws): {_g(w['pct_promoted_only_profitable'], 1)}% profitable promoted-only vs {_g(w['pct_family_profitable'], 1)}% family. **Naive baseline:** the promoted-only (dashboard) view is reported next to the family view everywhere.

## Segment / robustness checks
- By elasticity source: of the {r['n_skus']} reference SKUs, {r['n_estimated_elasticity']} use an estimated (shrunk) elasticity and {r['n_prior_or_family_elasticity']} a family median or prior; across all {d['n_skus']:,} SKUs, {d['source_counts'].get('prior', 0)} rely on the prior.
- By substitute strength: weak-substitute families have cannibalisation scaled by the configured cap.
- No individual-level or protected attributes are used (invoice-level data), so no person-level fairness check applies; customer mix (wholesale vs retail) is not modelled.
- Sensitivity: margin and outside share grid in `outputs/reference_sensitivity.csv`; four-parameter sweep in `outputs/sweep_draws.csv`.

## Known failure modes
Confounded price changes (clearance, mix) bias elasticities; text-based families can mix product types (fix with `config/family_overrides.csv`); basket confidence is not causal pull; MNL/IIA spreads sibling losses by share; baseline units are means over active weeks and overstate sporadic SKUs.

## Monitoring plan
Compare predicted vs realised family net on each controlled promotion; track elasticity drift and share of SKUs on the prior; re-fit monthly.

## Version
promo 0.1.0, seed {s['seed']}, config in `config/config.yaml`.
"""


