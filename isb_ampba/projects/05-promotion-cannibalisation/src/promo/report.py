def inject_readme(readme: Path, block: str) -> None:
    """Replace the content between RESULTS markers in README.md."""
    txt = readme.read_text(encoding="utf-8")
    if START in txt and END in txt:
        a, b = txt.index(START), txt.index(END) + len(END)
        txt = txt[:a] + block + txt[b:]
    else:
        txt += "\n" + block + "\n"
    readme.write_text(txt, encoding="utf-8")


def write_docs(summary: dict, root: Path) -> None:
    """Write DECISION_MEMO, MODEL_CARD, data_quality and the README results block."""
    docs = root / "docs"
    docs.mkdir(exist_ok=True)
    (docs / "DECISION_MEMO.md").write_text(memo(summary), encoding="utf-8")
    (docs / "MODEL_CARD.md").write_text(model_card(summary), encoding="utf-8")
    (docs / "data_quality.md").write_text(data_quality(summary), encoding="utf-8")
    readme = root / "README.md"
    if readme.exists():
        inject_readme(readme, results_block(summary))
